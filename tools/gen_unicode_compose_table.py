#!/usr/bin/env python3
"""
Generate src/frontend/unicode_compose_table.h: the data composeCanonical()
in src/frontend/utf8.cpp needs to put a letter and its combining marks
together without a platform library (#169).

The data comes from the Unicode Character Database, as Python's unicodedata
module carries it.  Only what Latin, Greek and Cyrillic need is taken:

  - the canonical composition pairs (letter, mark) -> precomposed letter
  - the combining class of each combining mark of those blocks
  - the letters whose canonical form is another code point (the Greek oxia
    letters, the Greek question mark) or a sequence that never composes

Usage:
  python tools/gen_unicode_compose_table.py            # write the header
  python tools/gen_unicode_compose_table.py --check    # exit 1 if it is out of date

The header records the Unicode version it was made from.  A Python with a
different version may produce a different table; composition pairs never
change for existing characters, so regenerate only on purpose.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
HEADER = REPO_ROOT / "src" / "frontend" / "unicode_compose_table.h"

# Basic Latin to Cyrillic Supplement; Latin Extended Additional and Greek
# Extended.  composeCanonical() leaves everything else as it came.
BLOCKS = ((0x0000, 0x052F), (0x1E00, 0x1FFF))


def covered():
    for lo, hi in BLOCKS:
        yield from range(lo, hi + 1)


def canonical(cp):
    """The canonical decomposition mapping of one code point, or []."""
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return []
    return [int(x, 16) for x in d.split()]


def build():
    inside = set(covered())
    pairs = {}     # (first, second) -> composed
    singles = {}   # cp -> [one or two code points]
    for cp in range(0x110000):
        parts = canonical(cp)
        if not parts:
            continue
        composes = (len(parts) == 2 and
                    unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp))
        if composes and all(p in inside for p in parts):
            # Includes the three signs "=", "<", ">" take U+0338 to become.
            pairs[(parts[0], parts[1])] = cp
        elif not composes and cp in inside:
            singles[cp] = parts
    marks = {cp: unicodedata.combining(chr(cp)) for cp in inside if unicodedata.combining(chr(cp))}

    # What the C++ relies on.
    for (first, second), composed in pairs.items():
        assert max(first, second, composed) <= 0xFFFF
        assert second in marks and first not in marks, hex(composed)
    for cp, parts in singles.items():
        assert len(parts) in (1, 2) and max(parts) <= 0xFFFF and cp >= 0x300, hex(cp)
    assert min(marks) >= 0x300
    return pairs, marks, singles


def render():
    pairs, marks, singles = build()
    out = []
    w = out.append
    w("/*")
    w("TGSpeechBox — canonical composition data for Latin, Greek and Cyrillic.")
    w("")
    w("GENERATED by tools/gen_unicode_compose_table.py; do not edit by hand.")
    w(f"Derived from the Unicode Character Database {unicodedata.unidata_version} (through Python's")
    w("unicodedata module).  Unicode data files are Copyright Unicode, Inc. and")
    w("used under the Unicode License v3 (https://www.unicode.org/license.txt).")
    w("*/")
    w("")
    w("#ifndef TGSB_FRONTEND_UNICODE_COMPOSE_TABLE_H")
    w("#define TGSB_FRONTEND_UNICODE_COMPOSE_TABLE_H")
    w("")
    w("namespace nvsp_frontend {")
    w("namespace unicode_compose {")
    w("")
    w("// Every code point here is below U+10000 and is kept in 16 bits.")
    w("")
    w("// A letter and a combining mark that are one precomposed letter.  Sorted by")
    w("// (first, second).")
    w("struct Pair { unsigned short first, second, composed; };")
    w("static const Pair kPairs[] = {")
    row = []
    for (first, second), composed in sorted(pairs.items()):
        row.append("{0x%04X,0x%04X,0x%04X}" % (first, second, composed))
        if len(row) == 4:
            w("  " + ", ".join(row) + ",")
            row = []
    if row:
        w("  " + ", ".join(row) + ",")
    w("};")
    w("")
    w("// The canonical combining class of each combining mark.  Sorted by cp.")
    w("struct Mark { unsigned short cp; unsigned char ccc; };")
    w("static const Mark kMarks[] = {")
    row = []
    for cp, ccc in sorted(marks.items()):
        row.append("{0x%04X,%d}" % (cp, ccc))
        if len(row) == 8:
            w("  " + ", ".join(row) + ",")
            row = []
    if row:
        w("  " + ", ".join(row) + ",")
    w("};")
    w("")
    w("// A code point whose canonical form is another code point, or two that do")
    w("// not compose back (second is 0 when there is one).  Sorted by cp.")
    w("struct Single { unsigned short cp, first, second; };")
    w("static const Single kSingles[] = {")
    for cp, parts in sorted(singles.items()):
        w("  {0x%04X,0x%04X,0x%04X},  // %s" % (cp, parts[0], parts[1] if len(parts) == 2 else 0,
                                              unicodedata.name(chr(cp), "")))
    w("};")
    w("")
    w("}  // namespace unicode_compose")
    w("}  // namespace nvsp_frontend")
    w("")
    w("#endif")
    return "\n".join(out) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = HEADER.read_text(encoding="utf-8") if HEADER.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{HEADER.relative_to(REPO_ROOT)} is out of date; run tools/gen_unicode_compose_table.py")
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")  # the platform's own line endings
    print(f"wrote {HEADER.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
